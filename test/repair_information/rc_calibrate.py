"""Fit the one `set_wire_rc` constant to the layers a design actually uses.

`estimate_parasitics -placement` prices every net from a single
resistance and capacitance. asap7 installs an absolute constant
corresponding to a lower-middle layer, and that constant is the whole
pre-route wire model: it is what makes placement's `min_period` 23%
pessimistic on a design whose routing lands elsewhere in the stack.

This study measured that the *ranking* the early repair consumes cannot
be improved by a better instrument -- the critical endpoints are
separated by less than the instrument's own error -- but that the
*magnitude* can, and every pre-route budget is set against the
magnitude. A calibration is the cheapest way to fix a magnitude: it
costs one number, computed once, and nothing per run. A throwaway global
route costs a route per repair.

The fit is a demand-weighted average of the platform's own per-layer
table, weighted by the microns of guide each layer carries in a routed
design:

    R_eff = sum(demand_i * R_i) / sum(demand_i)

which is the constant that would reproduce the design's total wire
resistance if every net were priced at one rate. It is deliberately not
a regression: ORFS already ships one (`correlateRC.py`, wrapped by
`//:rc.bzl`), it needs detailed route and two extractions, and it fits
*per layer* -- which is the right tool for a signoff RC table and the
wrong one for the single scalar `estimate_parasitics -placement`
consumes.

M1 is excluded by default. It is outside `MIN_ROUTING_LAYER`, carries
pin-level guides rather than routing, and its resistance is 2.4x M2's --
including it would drag the constant toward a layer no signal net routes
on.
"""

import argparse
import json
import re
from pathlib import Path

# The platform's per-layer table, parsed from its own setRC.tcl rather
# than copied, so a platform change cannot leave this file stale.
LAYER_RE = re.compile(
    r"set_layer_rc\s+-layer\s+(\S+)\s+-resistance\s+(\S+)\s+-capacitance\s+(\S+)"
)
WIRE_RE = re.compile(
    r"set_wire_rc\s+-(signal|clock)\s+-resistance\s+(\S+)\s+-capacitance\s+(\S+)"
)


def parse_setrc(text):
    """{layer: (R, C)} and {signal|clock: (R, C)} from a setRC.tcl."""
    layers = {name: (float(r), float(c)) for name, r, c in LAYER_RE.findall(text)}
    wires = {kind: (float(r), float(c)) for kind, r, c in WIRE_RE.findall(text)}
    if not layers or not wires:
        raise SystemExit("setRC.tcl parsed to nothing: the format changed")
    return layers, wires


def demand_weighted(layers, demand, exclude=("M1",)):
    """The single R and C that reproduce the routed design's totals.

    `demand` is {layer: microns of guide}. Layers the platform has no RC
    for are an error rather than a skip: silently dropping one would
    weight the average toward the layers that happen to be described.
    """
    total = 0.0
    r_sum = 0.0
    c_sum = 0.0
    for name, um in demand.items():
        if name in exclude or um <= 0:
            continue
        if name not in layers:
            raise SystemExit(f"{name} carries {um:.0f}um but has no RC in setRC.tcl")
        r, c = layers[name]
        total += um
        r_sum += um * r
        c_sum += um * c
    if total <= 0:
        raise SystemExit("no routable demand: nothing to fit")
    return r_sum / total, c_sum / total


def demand_from_probe(path):
    """{layer: demand_um} out of an endpoint_slacks.tcl result."""
    data = json.loads(Path(path).read_text())
    if not data.get("layers"):
        raise SystemExit(f"{path}: no per-layer demand; was this a routed arm?")
    return {row["layer"]: float(row["demand_um"]) for row in data["layers"]}


def render(r, c, note):
    """A LAYER_PARASITICS_FILE that keeps the platform table and replaces
    only the scalar the placement estimator reads."""
    return f"""# Generated by rc_calibrate.py -- do not edit.
#
# {note}
#
# The platform's per-layer table is installed unchanged: it is what
# `estimate_parasitics -global_routing` and the extraction use, and it is
# not what this study found to be wrong. Only the single signal constant
# `estimate_parasitics -placement` prices every net from is replaced.
source $::env(PLATFORM_DIR)/setRC.tcl

set_wire_rc -signal -resistance {r:.6g} -capacitance {c:.6g}

puts "RC_CAL signal wire R={r:.6g} C={c:.6g}"
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--probe", required=True, help="a routed arm's probe JSON")
    ap.add_argument("--setrc", required=True, help="the platform's setRC.tcl")
    ap.add_argument("--out", help="write the calibrated tcl here")
    args = ap.parse_args()

    layers, wires = parse_setrc(Path(args.setrc).read_text())
    demand = demand_from_probe(args.probe)
    r, c = demand_weighted(layers, demand)

    pr, pc = wires["signal"]
    note = (
        f"demand-weighted over the routed layer mix of {Path(args.probe).stem}; "
        f"platform signal constant was R={pr:.6g} C={pc:.6g}, "
        f"so R moves {100 * (r - pr) / pr:+.1f}% and C {100 * (c - pc) / pc:+.1f}%"
    )
    text = render(r, c, note)
    if args.out:
        Path(args.out).write_text(text)
    print(note)


if __name__ == "__main__":
    main()
