"""Write the real-design packing problems as a C++ table for the gtest.

Each distinct problem mpl's annealer was asked, from every design's study
dumps, with whether the annealer placed it. Block names are dropped: the
problems are sizes only.

usage: make_table.py <out.inc> <design>=<dump dir>... [--xiangshan plan.bzl]
"""

import argparse
import ast
import glob
import json
import re


def anonymize(text):
    lines = text.strip().split("\n")
    out = [lines[0]]
    for k, line in enumerate(lines[1:]):
        parts = line.split()
        parts[1] = f"b{k}"
        out.append(" ".join(parts))
    return out


def xiangshan(plan_path):
    """XSTile's parent: its five hardened blocks and three register files
    inside the parent core, asap7 at 1000 DBU per micron."""
    text = open(plan_path).read()
    plan = ast.literal_eval(text[text.index("{") :])
    dbu = 1000

    def box(area):
        x0, y0, x1, y1 = map(float, area.split())
        return round((x1 - x0) * dbu), round((y1 - y0) * dbu)

    width, height = box(plan["parent"]["CORE_AREA"])
    blocks = [box(m["DIE_AREA"]) for m in plan["macros"].values()]
    blocks += [
        (round(n["w_um"] * dbu), round(n["h_um"] * dbu))
        for n in plan["parent"]["netlists"]
    ]
    lines = [f"P xiangshan_XSTile {width} {height} {len(blocks)}"]
    lines += [f"B b{k} R 1 {w} {h}" for k, (w, h) in enumerate(blocks)]
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("out")
    parser.add_argument("designs", nargs="+")
    parser.add_argument("--xiangshan")
    args = parser.parse_args()
    entries = {}
    for spec in args.designs:
        design, directory = spec.split("=", 1)
        for path in sorted(glob.glob(f"{directory}/mpl_dump.*.jsonl")):
            for row in open(path):
                r = json.loads(row)
                lines = anonymize(r["packing"])
                body = "\n".join(lines[1:])
                head = lines[0].split()
                key = (design, head[2], head[3], body)
                placed = bool(r["valid"])
                entries[key] = entries.get(key, False) or placed
    # The annealer asks one block set against many outlines; keep, per block
    # set, the largest outline it placed and the largest it did not.
    keep = {}
    for (design, width, height, body), placed in entries.items():
        area = int(width) * int(height)
        slot = (design, body, placed)
        if slot not in keep or area > keep[slot][0]:
            keep[slot] = (area, width, height)
    # A cluster placement is asked at each standard cell utilization the
    # annealer tries: same outline and blocks, different areas. Keep the
    # densest and the sparsest of each.
    groups = {}
    for (design, body, placed), (_, width, height) in keep.items():
        n = body.count("\n") + 1 if body else 0
        filled = sum(int(t) for line in body.split("\n") for t in line.split()[-1:])
        groups.setdefault((design, width, height, n, placed), []).append((filled, body))
    rows = []
    for (design, width, height, n, placed), bodies in groups.items():
        bodies.sort()
        kept = [bodies[0][1]]
        if bodies[-1][1] != bodies[0][1]:
            kept.append(bodies[-1][1])
        for body in kept:
            rows.append(
                (design, placed, f"P {design} {width} {height} {n}\n{body}".strip())
            )
    if args.xiangshan:
        rows.append(("xiangshan", True, "\n".join(xiangshan(args.xiangshan))))
    with open(args.out, "w") as f:
        f.write(
            "// Generated by make_table.py from mpl's study dumps of ORFS\n"
            "// designs and XiangShan's plan; do not edit.\n"
            "// {design, annealer placed it, problem}\n"
        )
        for design, placed, problem in rows:
            f.write(
                f'{{"{design}", {"true" if placed else "false"}, '
                f'R"({problem}\n)"}},\n'
            )
    print(f"{len(rows)} problems")


if __name__ == "__main__":
    main()
