"""`bazelisk run //:export -- <dest> <orfs_flow target>`: a flow out to ORFS.

The off-ramp. Writes <dest>/config.mk and every input the flow reads
under <dest>/inputs/: an ORFS design, run with ORFS's make as usual,
`make DESIGN_CONFIG=<dest>/config.mk` in an ORFS checkout's flow/. Nothing
in <dest> refers to this workspace: copy it to another machine, mail it,
hand it to someone who has never run Bazel.

The values are the ones Bazel configures each stage with: the stage's own
config.mk, the one //:dirty installs, for every stage of the flow, merged
into one. A stage's config holds only that stage's variables, and a later
stage's can be generated by an earlier stage's actions, so no single
stage's config tells the whole story; Bazel builds each stage's config
(an earlier stage first, where a later one's variables come from it).

A macro that is itself an orfs_flow() becomes one of ORFS's BLOCKS: its
own config.mk in <dest>/<module>/, which ORFS's make builds, abstracts
and hands to the parent, as in ORFS's designs/asap7/aes-block. The inputs
of every block share <dest>/inputs/.

--abstracts keeps the macros the files they are instead: each macro's
abstract, as built, under inputs/, for a block ORFS's BLOCKS cannot
make, such as a mocked one.

--snapshot-macro-placement replaces each flow's macro placement, whatever
decided it, with what the build decided: a MACRO_PLACEMENT_TCL, written
from the flow's 2_floorplan.odb by snapshot_macros.tcl, that puts every
macro back where it was. ORFS's make then places the macros the same way
without the tool, script or plan that placed them; --drop names the
variables only that tool read. A flow whose floorplan dissolves register
files placed as macros (AUTO_MEMORIES_MACRO_PLACE) is refused: its
2_floorplan.odb no longer has them.

A flow that synthesises with yosys ships yosys's netlist as built,
1_2_yosys.v named by SYNTH_NETLIST_FILES beside its config.mk, so make skips synthesis. Every
value that names a file made for the export, by Bazel or by the export,
is written with ?=: `make ... SYNTH_NETLIST_FILES=` synthesises from the
RTL.

What cannot be said in one config.mk is refused, naming it and this file:
a variable two stages set differently, a value that is an earlier stage's
result, a mocked macro. A project with its own ORFS changes is expected to
have an AI patch this file to match.

    bazelisk run //:export -- \\
        ~/OpenROAD-flow-scripts/flow/designs/asap7/gcd-bazel //imported/asap7/gcd:gcd
    cd ~/OpenROAD-flow-scripts/flow
    make DESIGN_CONFIG=./designs/asap7/gcd-bazel/config.mk

    bazelisk run //:export -- --snapshot-macro-placement \\
        ~/OpenROAD-flow-scripts/flow/designs/asap7/wide_top \\
        //test/regfile/macro:wide_top_hard
"""

import argparse
import os
import re
import shutil
import subprocess
import sys

MARKER = "# Exported by `bazelisk run //:export`"

STAGES = ["synth", "floorplan", "place", "cts", "grt", "route", "final"]

# The ORFS checkout supplies these: where its platform lives, and where a
# run writes.
DROPPED = {"WORK_HOME", "PLATFORM_DIR", "FLOW_VARIANT"}

FIRST = ["PLATFORM", "DESIGN_NAME", "DESIGN_NICKNAME"]

# The .odb a stage leaves: what generate_abstract's ABSTRACT_SOURCE names.
STAGE_ODB = {
    "floorplan": "2_floorplan",
    "place": "3_place",
    "cts": "4_cts",
    "grt": "5_1_grt",
    "route": "5_route",
    "final": "6_final",
}

# Where a block's abstract reaches its parent: ORFS's BLOCKS appends the
# block's own to these, so the export takes Bazel's out.
BLOCK_VARIABLES = {
    "ADDITIONAL_LEFS",
    "ADDITIONAL_LIBS",
    "ADDITIONAL_TYP_LIBS",
    "ADDITIONAL_FAST_LIBS",
    "ADDITIONAL_SLOW_LIBS",
    "ADDITIONAL_GDS",
}

SNAPSHOT_TCL = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "snapshot_macros.tcl"
)

EXPORT = re.compile(r"^export ([A-Za-z_][A-Za-z0-9_]*)\?=(.*)$")


class Refused(Exception):
    """A flow export cannot map; the message names it and what to do."""


def refuse(msg):
    raise Refused(
        msg + "\n(tools/ramp/export_design.py is the file to patch; docs/ramps.md)"
    )


def read_manifest(path):
    """{tree path: (execroot path, kind)} from a stage's deps manifest."""
    entries = {}
    with open(path) as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 3:
                entries[parts[1]] = (parts[0], parts[2])
    return entries


def read_config(path):
    """(exports, includes) of a stage's short config.mk."""
    exports, includes = {}, []
    with open(path) as f:
        for line in f:
            line = line.rstrip("\n")
            m = EXPORT.match(line)
            if m:
                exports[m.group(1)] = m.group(2)
            elif line.startswith("include "):
                includes.append(line[len("include ") :].strip())
            elif line.strip():
                refuse("{}: a line export does not read: {}".format(path, line))
    return exports, includes


def merge(stage_configs):
    """One {variable: value} from each stage's (stage, exports)."""
    merged, where = {}, {}
    for stage, exports in stage_configs:
        for k, v in exports.items():
            if k in DROPPED:
                continue
            if k in merged and merged[k] != v:
                refuse(
                    "{} is {!r} in {} but {!r} in {}: one config.mk cannot say"
                    " both".format(k, merged[k], where[k], v, stage)
                )
            merged[k] = v
            where[k] = stage
    return merged


def strip_blocks(exports, prefixes):
    """A stage's exports without the files of the blocks under prefixes.

    ORFS's BLOCKS gives the parent each block's abstract; Bazel's names
    for them (a pre-layout .lib before CTS, the abstract after) go.
    """
    out = {}
    for k, v in exports.items():
        words = v.split()
        kept = [w for w in words if not w.startswith(tuple(prefixes))]
        if len(kept) == len(words):
            out[k] = v
            continue
        if k not in BLOCK_VARIABLES:
            refuse(
                "{} names a block's result ({}): ORFS's BLOCKS hands a parent"
                " its blocks' abstracts in {} only".format(
                    k,
                    [w for w in words if w not in kept][0],
                    ", ".join(sorted(BLOCK_VARIABLES)),
                )
            )
        if kept:
            out[k] = " ".join(kept)
    return out


# A macro's pre-layout .lib: <pkg>/results/<platform>/<macro>/<..>pre_layout/<file>
PRE_LAYOUT = re.compile(r"^(.*/results/[^/]+/[^/]+/)[^/]*pre_layout/([^/]+)$")


def strip_pre_layout(stage_configs):
    """Each stage's exports without a macro's pre-layout .lib that another
    stage names the macro's own .lib for.

    Bazel gives the stages before CTS a macro's pre-layout .lib and the
    later ones the abstract's own; one config.mk says one, the abstract's.
    A flow that ends before CTS keeps its pre-layout .lib: it has no other.
    """
    own = set()
    for _, exports in stage_configs:
        for k, v in exports.items():
            if k in BLOCK_VARIABLES:
                for w in v.split():
                    m = re.match(r"^(.*/results/[^/]+/[^/]+/)[^/]+/([^/]+)$", w)
                    if m and not PRE_LAYOUT.match(w):
                        own.add(m.groups())
    out = []
    for stage, exports in stage_configs:
        stripped = {}
        for k, v in exports.items():
            if k in BLOCK_VARIABLES:
                kept = " ".join(
                    w
                    for w in v.split()
                    if not (PRE_LAYOUT.match(w) and PRE_LAYOUT.match(w).groups() in own)
                )
                if v and not kept:
                    continue  # the stage named only what is taken out
                v = kept
            stripped[k] = v
        out.append((stage, stripped))
    return out


def platform_relative(platform, path):
    """$(PLATFORM_DIR)/... for a file of the ORFS platform, else None."""
    m = re.search(
        r"(?:^|/)flow/(?:[^/]+/)?platforms/" + re.escape(platform) + "/(.*)$", path
    )
    if m and path.startswith("external/"):
        return "$(PLATFORM_DIR)/" + m.group(1)
    return None


class Inputs:
    """Copies a flow's input files under <dest>/inputs/."""

    def __init__(
        self, execroot, dest, manifest, platform, pkg, copied=None, ensure=None
    ):
        self.execroot = execroot
        # called with an input's execroot path when it is not built yet
        self.ensure = ensure
        self.pkg = pkg
        self.dest = dest
        self.manifest = manifest
        self.platform = platform
        # execroot path -> inputs-relative path, shared by a parent and
        # its blocks, which copy into the same inputs/
        self.copied = {} if copied is None else copied
        # the variables that name a file Bazel built: config.mk says ?=
        self.generated = set()

    def rewrite(self, var, value):
        """A value with each word that is a file replaced by its export path."""
        words = []
        for w in value.split():
            hit = self.manifest.get("_main/" + w)
            if hit is None:
                words.append(w)
                continue
            src, kind = hit
            if kind == "result":
                refuse(
                    "{} names {}, an earlier stage's result: an export runs the"
                    " flow from RTL, and ORFS's make writes its own".format(var, w)
                )
            if src.startswith("bazel-out/"):
                self.generated.add(var)
            rel = platform_relative(self.platform, src)
            words.append(rel if rel else "$(EXPORT_DIR)/inputs/" + self.copy(src, w))
        return " ".join(words)

    def copy(self, src, word):
        if src in self.copied:
            return self.copied[src]
        rel = word
        if rel.startswith(self.pkg + "/"):
            rel = rel[len(self.pkg) + 1 :]
        elif rel.startswith("external/"):
            rel = rel[len("external/") :]
        if rel in self.copied.values():
            refuse("two inputs would be copied to inputs/{}: {}".format(rel, src))
        to = os.path.join(self.dest, "inputs", rel)
        os.makedirs(os.path.dirname(to), exist_ok=True)
        frm = os.path.join(self.execroot, src)
        if not os.path.exists(frm) and self.ensure:
            self.ensure(src)
        if os.path.isdir(frm):
            shutil.copytree(frm, to, dirs_exist_ok=True)
        else:
            shutil.copy2(frm, to)
        os.chmod(to, os.stat(to).st_mode | 0o200)
        self.copied[src] = rel
        return rel


# ORFS's make target for a flow's last stage.
MAKE_TARGET = {"final": "finish"}


def write_config(dest, flow, merged, includes, last, depth=0, parent=None, defaults=()):
    """dest/config.mk; a block's, depth directories below the export's.

    defaults: the variables written with ?=, the files made for this
    export rather than written by hand.
    """
    if parent is None:
        lines = [
            MARKER + " from {}.".format(flow),
            "# An ORFS design: in an ORFS checkout's flow/,",
            "#   make DESIGN_CONFIG=<this file>{}".format(
                "" if last == "final" else " " + MAKE_TARGET.get(last, last)
            ),
        ]
        if last != "final":
            lines.append("# Bazel builds this flow to {} only.".format(last))
    else:
        source = merged.get("ABSTRACT_SOURCE", STAGE_ODB["final"])
        lines = [
            MARKER + " from {}.".format(flow),
            "# One of {}'s BLOCKS: its make builds this block with".format(parent),
            "# generate_abstract, which runs it to finish, as ORFS always does,",
            "# and abstracts {}.odb.".format(source),
        ]
        if last != "final":
            lines.append(
                "# Bazel builds this flow to {} only: route and finish run on"
                " ORFS's defaults.".format(last)
            )
    if merged.get("SYNTH_HDL_FRONTEND") == "slang":
        lines.append(
            "# Synthesis reads the Verilog with slang: yosys needs the yosys-slang"
            " plugin."
        )
    if defaults:
        lines.append(
            "# A ?= value is a file made for you, by Bazel or by the export:"
            " override it"
        )
        lines.append("# on the make line.")
        if "SYNTH_NETLIST_FILES" in defaults:
            lines.append("#   make ... SYNTH_NETLIST_FILES=   synthesises from the RTL")
        if "MACRO_PLACEMENT_TCL" in defaults:
            lines.append(
                "#   make ... MACRO_PLACEMENT_TCL=   places the macros with"
                " ORFS's placer"
            )
    lines += [
        "",
        "# The export's directory, wherever it is copied to.",
        "export EXPORT_DIR := $(abspath $(dir $(lastword $(MAKEFILE_LIST))){})".format(
            "/.." * depth
        ),
        "",
    ]
    for k in [k for k in FIRST if k in merged] + sorted(set(merged) - set(FIRST)):
        lines.append(
            "export {} {} {}".format(k, "?=" if k in defaults else "=", merged[k])
        )
    for inc in includes:
        lines.append("include {}".format(inc))
    with open(os.path.join(dest, "config.mk"), "w") as f:
        f.write("\n".join(lines) + "\n")


def orfs_flow_dir(path):
    """The ORFS flow/ directory a path is inside, if any."""
    d = path
    while d != os.path.dirname(d):
        if os.path.isfile(os.path.join(d, "Makefile")) and os.path.isfile(
            os.path.join(d, "scripts", "variables.mk")
        ):
            return d
        d = os.path.dirname(d)
    return None


def next_step(dest, merged, last):
    """What to type to run the export, and a note when it shares results."""
    target = "" if last == "final" else " " + MAKE_TARGET.get(last, last)
    flow = orfs_flow_dir(dest)
    if not flow:
        return [
            "next:   make -C <ORFS>/flow DESIGN_CONFIG={}/config.mk{}".format(
                dest, target
            )
        ]
    lines = [
        "next:   cd {}".format(flow),
        "        make DESIGN_CONFIG=./{}/config.mk{}".format(
            os.path.relpath(dest, flow), target
        ),
    ]
    nickname = merged.get("DESIGN_NICKNAME") or merged.get("DESIGN_NAME")
    results = os.path.join(
        flow, "results", merged.get("PLATFORM", ""), nickname, "base"
    )
    if os.path.isdir(results):
        lines.append(
            "note:   {} holds an earlier run of {}: add FLOW_VARIANT=bazel to keep"
            " this one apart".format(os.path.relpath(results, flow), nickname)
        )
    return lines


def bazelisk(ws, *args):
    cmd = ["bazelisk"] + os.environ.get("EXPORT_STARTUP_OPTS", "").split() + list(args)
    return subprocess.run(cmd, cwd=ws, capture_output=True, text=True)


def stage_targets(ws, pkg, base):
    """The stage targets of the flow pkg:base_*, in flow order, that exist."""
    r = bazelisk(ws, "query", "--output=label", "//{}:*".format(pkg))
    if r.returncode:
        refuse("bazelisk query //{}:* failed:\n{}".format(pkg, r.stderr[-2000:]))
    labels = set(r.stdout.split())
    targets = []
    for s in STAGES:
        t = "//{}:{}_{}".format(pkg, base, s)
        if t in labels:
            targets.append((s, t))
    if not targets or targets[0][0] != "synth":
        refuse("//{}:{} has no {}_synth: is it an orfs_flow()?".format(pkg, base, base))
    return targets


def query_lines(ws, *args):
    r = bazelisk(ws, "query", *args)
    if r.returncode:
        refuse("bazelisk query {} failed:\n{}".format(" ".join(args), r.stderr[-2000:]))
    return r.stdout.splitlines()


def group_files(ws, target, group):
    r = bazelisk(ws, "cquery", "--output=files", "--output_groups=" + group, target)
    if r.returncode:
        refuse("bazelisk cquery {} failed:\n{}".format(target, r.stderr[-2000:]))
    return r.stdout.split()


def short_path(path):
    """A bazel-out/<config>/bin/ path as the workspace-relative path."""
    m = re.match(r"bazel-out/[^/]+/bin/(.*)$", path)
    return m.group(1) if m else path


class Design:
    """One flow of the export: the top, or a block below it."""

    def __init__(self, pkg, base, targets):
        self.pkg = pkg
        self.base = base
        self.targets = targets
        self.blocks = []
        self.abstract_stage = None  # a block's: the stage its abstract is cut at
        self.prefix = None  # a block's: where its results are, as its parent names them
        self.rel = ""  # the directory under the export, "" for the top

    @property
    def label(self):
        return "//{}:{}".format(self.pkg, self.base)


def discover(ws, pkg, base, abstracts=False):
    """The flow pkg:base and, recursively, the flows its macros are.

    With abstracts, the macros stay the files they are, and none is a block.
    """
    design = Design(pkg, base, stage_targets(ws, pkg, base))
    if abstracts:
        return design
    synth = design.targets[0][1]
    for line in query_lines(
        ws, "--output=label_kind", "labels(deps, {})".format(synth)
    ):
        kind, label = line.split()[0], line.split()[-1]
        if kind == "orfs_macro":
            refuse(
                "{} is a mocked abstract (orfs_flow(mock_area = ...)): ORFS's BLOCKS"
                " gives the parent the block's own abstract, of another size;"
                " --abstracts ships every macro's abstract as built".format(label)
            )
        if kind != "orfs_abstract_rule":
            continue  # a macro of another kind: its files are inputs, as ever
        src = query_lines(ws, "labels(src, {})".format(label))
        if len(src) != 1:
            refuse("{} abstracts {}: one stage expected".format(label, src))
        bpkg, bname = src[0].lstrip("@").split("//", 1)[1].split(":")
        bbase, stage = bname.rsplit("_", 1)
        if stage not in STAGE_ODB:
            refuse("{} abstracts {}, not a stage export knows".format(label, src[0]))
        block = discover(ws, bpkg, bbase)
        block.abstract_stage = stage
        lefs = [f for f in group_files(ws, label, "default") if f.endswith(".lef")]
        if len(lefs) != 1:
            refuse("{} has no one .lef: {}".format(label, lefs))
        block.prefix = os.path.dirname(os.path.dirname(short_path(lefs[0]))) + "/"
        design.blocks.append(block)
    return design


def walk(design):
    yield design
    for b in design.blocks:
        yield from walk(b)


def openroad_exe(ws, execroot, target):
    """The openroad the flow's stages run, exec configuration, built."""
    label = query_lines(ws, "labels(openroad, {})".format(target))
    if len(label) != 1:
        refuse("{} names no one openroad: {}".format(target, label))
    name = label[0].rsplit(":", 1)[-1]
    r = bazelisk(
        ws,
        "cquery",
        "--output=starlark",
        "--starlark:expr=[f.path for f in providers(target)['DefaultInfo']"
        ".default_runfiles.files.to_list() if f.owner != None and f.owner.name"
        " == {!r} and f.basename == {!r}]".format(name, name),
        target,
    )
    paths = re.findall(r'"([^"]+)"', r.stdout)
    if r.returncode or len(paths) != 1:
        refuse("no one {} in {}'s runfiles:\n{}".format(name, target, r.stderr[-2000:]))
    exe = os.path.join(execroot, paths[0])
    if not os.path.isfile(exe):
        refuse("{} was not built or downloaded: build {} first".format(exe, target))
    return exe


def snapshot(ws, execroot, design, dest, openroad):
    """design's macro placement as dest/<rel>/macro_placement.tcl; None with no macros."""
    target = dict(design.targets).get("floorplan")
    if target is None:
        refuse("{} has no floorplan stage to snapshot".format(design.label))
    odb = [f for f in group_files(ws, target, "2_floorplan.odb") if f.endswith(".odb")]
    if len(odb) != 1:
        refuse("{} has no one 2_floorplan.odb: {}".format(target, odb))
    out = os.path.join(dest, design.rel, "macro_placement.tcl")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    r = subprocess.run(
        [openroad, "-no_init", "-no_splash", "-exit", SNAPSHOT_TCL],
        env=dict(
            os.environ,
            SNAPSHOT_ODB=os.path.join(execroot, odb[0]),
            SNAPSHOT_OUT=out,
            SNAPSHOT_FROM=design.label,
        ),
        capture_output=True,
        text=True,
    )
    m = re.search(r"snapshot_macros.tcl: macros (\d+)", r.stdout)
    if r.returncode or not m:
        refuse(
            "snapshot_macros.tcl on {} failed:\n{}".format(
                odb[0], (r.stdout + r.stderr)[-2000:]
            )
        )
    if m.group(1) == "0":
        return None
    print("export: {} macros of {} snapshot".format(m.group(1), design.label))
    return "$(EXPORT_DIR)/" + os.path.join(design.rel, "macro_placement.tcl")


def wants_netlist(merged):
    """Whether a flow's export ships the netlist Bazel's yosys made.

    Not for SYNTH_USE_SYN: ORFS's OpenROAD synthesis ignores a netlist.
    Not where the flow names its own.
    """
    return merged.get("SYNTH_USE_SYN") != "1" and "SYNTH_NETLIST_FILES" not in merged


def netlist(ws, execroot, design, dest):
    """design's yosys netlist, 1_2_yosys.v, beside its config.mk, as config.mk
    names it: the file ORFS's synthesis copies SYNTH_NETLIST_FILES to."""
    synth = design.targets[0][1]
    build(ws, "1_2_yosys.v", [synth])
    v = [f for f in group_files(ws, synth, "1_2_yosys.v") if f.endswith("1_2_yosys.v")]
    if len(v) != 1:
        refuse("{} has no one 1_2_yosys.v: {}".format(synth, v))
    to = os.path.join(dest, design.rel, "1_2_yosys.v")
    os.makedirs(os.path.dirname(to), exist_ok=True)
    shutil.copy2(os.path.join(execroot, v[0]), to)
    os.chmod(to, os.stat(to).st_mode | 0o200)
    return "$(EXPORT_DIR)/" + os.path.join(design.rel, "1_2_yosys.v")


def read_stages(ws, execroot, design, abstracts=False):
    """(stage configs, manifest, includes, where) of a design's stages.

    where: {execroot path: the first stage target that reads it}.
    """
    stage_configs, manifest, includes, where = [], {}, [], {}
    prefixes = [b.prefix for b in design.blocks]
    for stage, target in design.targets:
        files = group_files(ws, target, "deps_scripts")
        man = [f for f in files if f.endswith("_deps_manifest.txt")]
        cfg = [f for f in files if f.endswith(".short.mk")]
        if len(man) != 1 or len(cfg) != 1:
            refuse(
                "{} has no deps manifest and config: is it an ORFS stage?".format(
                    target
                )
            )
        entries = read_manifest(os.path.join(execroot, man[0]))
        for src, _ in entries.values():
            where.setdefault(src, target)
        manifest.update(entries)
        exports, incs = read_config(os.path.join(execroot, cfg[0]))
        stage_configs.append((stage, strip_blocks(exports, prefixes)))
        includes += [i for i in incs if i not in includes]
    if abstracts:
        stage_configs = strip_pre_layout(stage_configs)
    return stage_configs, manifest, includes, where


def build(ws, groups, labels, extra=()):
    """bazelisk build of labels' output groups, or a refusal."""
    r = subprocess.run(
        ["bazelisk"]
        + os.environ.get("EXPORT_STARTUP_OPTS", "").split()
        + ["build", "--output_groups=" + groups]
        + list(extra)
        + os.environ.get("EXPORT_BUILD_OPTS", "").split()
        + list(labels),
        cwd=ws,
    )
    if r.returncode:
        refuse(
            "bazelisk build --output_groups={} {} failed".format(
                groups, " ".join(labels)
            )
        )


def export_flow(
    ws, flow, variant, dest, snapshot_macros=False, drop=(), abstracts=False
):
    pkg, name = flow.split("//", 1)[1].split(":")
    base = name + ("_" + variant if variant and variant != "base" else "")
    top = discover(ws, pkg, base, abstracts)
    designs = list(walk(top))
    labels = [t for d in designs for _, t in d.targets]
    print(
        "export: building the configs of {} stages of {} flows, and their"
        " synthesis inputs".format(len(labels), len(designs))
    )
    # A later stage's deps_inputs include the stages before it's reports,
    # which would build the whole flow; synthesis's are the RTL and the
    # macros. Any other input is built when it is copied (ensure, below).
    build(ws, "deps_scripts", labels)
    build(ws, "deps_inputs", [d.targets[0][1] for d in designs])
    if snapshot_macros:
        # the floorplan .odb, and the openroad that reads it: a stage
        # target's tool, so the exec configuration the remote cache has
        build(
            ws,
            "2_floorplan.odb",
            [t for d in designs for s, t in d.targets if s == "floorplan"],
            ["--remote_download_regex=.*/openroad$"],
        )
    execroot = bazelisk(ws, "info", "execution_root").stdout.strip()
    ensured = set()

    def ensure(where):
        def built(src):
            target = where.get(src)
            if target is None or target in ensured:
                refuse("{} is not built, and no stage builds it".format(src))
            ensured.add(target)
            print("export: building {}'s inputs, for {}".format(target, src))
            build(ws, "deps_inputs", [target])

        return built

    copied = {}
    unused = set(drop)
    steps = None

    def export(design, parent, depth):
        """Writes design's config.mk; parent is (label, nickname, rel) for a block."""
        nonlocal steps
        stage_configs, manifest, includes, where = read_stages(
            ws, execroot, design, abstracts
        )
        merged = merge(stage_configs)
        for k in drop:
            if merged.pop(k, None) is not None:
                unused.discard(k)
        platform = merged.get("PLATFORM")
        if not platform:
            refuse("{} sets no PLATFORM".format(design.label))
        if parent is not None:
            module = merged.get("DESIGN_NAME")
            design.rel = os.path.join(parent[2], module)
            merged["DESIGN_NICKNAME"] = "{}_{}".format(parent[1], module)
            if design.abstract_stage != "final":
                merged["ABSTRACT_SOURCE"] = STAGE_ODB[design.abstract_stage]
        nickname = merged.get("DESIGN_NICKNAME") or merged.get("DESIGN_NAME")
        names = []
        for b in design.blocks:
            export(b, (design.label, nickname, design.rel), depth + 1)
            names.append(os.path.basename(b.rel))
        if len(set(names)) != len(names) or "inputs" in names:
            refuse(
                "{}'s blocks are modules {}: ORFS's BLOCKS needs a directory, so a"
                " distinct module other than inputs, for each".format(
                    design.label, names
                )
            )
        if names:
            merged["BLOCKS"] = " ".join(sorted(names))
            # ORFS's Makefile names the blocks' results before variables.mk
            # defaults DESIGN_NICKNAME to DESIGN_NAME, so a parent says it
            merged["DESIGN_NICKNAME"] = nickname
        if snapshot_macros and merged.get("AUTO_MEMORIES_MACRO_PLACE"):
            refuse(
                "{} sets AUTO_MEMORIES_MACRO_PLACE: those register files are"
                " macros only until the floorplan dissolves them into cells, so its"
                " 2_floorplan.odb has no placement of them to snapshot".format(
                    design.label
                )
            )
        made = set()
        if wants_netlist(merged):
            merged["SYNTH_NETLIST_FILES"] = netlist(ws, execroot, design, dest)
            made.add("SYNTH_NETLIST_FILES")
        if snapshot_macros:
            placement = snapshot(
                ws,
                execroot,
                design,
                dest,
                openroad_exe(ws, execroot, dict(design.targets)["floorplan"]),
            )
            if placement:
                merged["MACRO_PLACEMENT_TCL"] = placement
                made.add("MACRO_PLACEMENT_TCL")
        here = os.path.join(dest, design.rel)
        os.makedirs(here, exist_ok=True)
        inputs = Inputs(
            execroot, dest, manifest, platform, design.pkg, copied, ensure(where)
        )
        merged = {k: inputs.rewrite(k, v) for k, v in merged.items()}
        incs = [inputs.rewrite("include", i) for i in includes]
        last = design.targets[-1][0]
        write_config(
            here,
            design.label,
            merged,
            incs,
            last,
            depth=depth,
            parent=None if parent is None else parent[0],
            defaults=made | inputs.generated,
        )
        if parent is None:
            steps = next_step(dest, merged, last)

    export(top, None, 0)
    if unused:
        refuse(
            "--drop {}: no flow of the export sets it".format(" ".join(sorted(unused)))
        )
    return copied, steps


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("dest", help="the directory to write; replaced if an export")
    ap.add_argument("flow", help="an orfs_flow() label, //pkg:name")
    ap.add_argument("--variant", help="the flow's variant, if not base")
    ap.add_argument(
        "--snapshot-macro-placement",
        action="store_true",
        help="place each flow's macros where the build placed them",
    )
    ap.add_argument(
        "--drop",
        action="append",
        default=[],
        metavar="VAR",
        help="leave VAR out of every config.mk: a variable only the replaced"
        " macro placement read (repeat for each)",
    )
    ap.add_argument(
        "--abstracts",
        action="store_true",
        help="ship each macro's abstract as built instead of making the macros"
        " that are flows ORFS BLOCKS",
    )
    args = ap.parse_args(argv)
    if args.drop and not args.snapshot_macro_placement:
        ap.error("--drop goes with --snapshot-macro-placement")

    ws = os.environ.get("BUILD_WORKSPACE_DIRECTORY", os.getcwd())
    cwd = os.environ.get("BUILD_WORKING_DIRECTORY", ws)
    dest = os.path.abspath(os.path.join(cwd, os.path.expanduser(args.dest)))
    flow = args.flow if args.flow.startswith(("//", "@")) else "//" + args.flow
    if ":" not in flow:
        flow += ":" + flow.rsplit("/", 1)[-1]
    try:
        config = os.path.join(dest, "config.mk")
        if os.path.exists(dest) and os.listdir(dest):
            if not (os.path.isfile(config) and open(config).read().startswith(MARKER)):
                refuse(
                    "{} exists and is not an export: refusing to replace it".format(
                        dest
                    )
                )
            shutil.rmtree(dest)
        os.makedirs(dest, exist_ok=True)
        copied, steps = export_flow(
            ws,
            flow,
            args.variant,
            dest,
            args.snapshot_macro_placement,
            args.drop,
            args.abstracts,
        )
    except Refused as e:
        print("export: " + str(e), file=sys.stderr)
        return 1
    shown = os.path.relpath(dest, cwd)
    if shown.startswith(".."):
        shown = dest
    print("export: {} inputs into {}".format(len(copied), shown))
    for line in steps:
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
