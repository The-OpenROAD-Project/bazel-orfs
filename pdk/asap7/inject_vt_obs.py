"""Inject ASAP7 VT implant OBS layers (RVTN/P, LVTN/P, SLVTN/P) into LEF macros.

Upstream asap7sc7p5t_28 LEFs (including the 64 macros generated by GDS-to-LEF
in PR #13) omit the RVTN/RVTP, LVTN/LVTP and SLVTN/SLVTP implant layers that
ORFS's vendored LEFs carry in each cell's OBS section. OpenROAD's
Resizer::cellVTType() hashes IMPLANT layers in OBS to distinguish VT classes
for buffer selection and vt_swap; without them all VTs collapse into vt_index 0.
"""

import argparse
import re
import shutil
import sys
from pathlib import Path

_MACRO_RE = re.compile(r"(^MACRO\s+(\S+)\b.*?^END\s+\2\b)", re.M | re.S)
_SIZE_RE = re.compile(r"^\s*SIZE\s+([0-9.]+)\s+BY\s+([0-9.]+)\s*;", re.M)


def inject_macro_vt(macro_text, vt_tag):
    vtn = f"{vt_tag}VTN"
    vtp = f"{vt_tag}VTP"
    if f"LAYER {vtn}" in macro_text:
        return macro_text
    m_size = _SIZE_RE.search(macro_text)
    if not m_size:
        raise ValueError(f"MACRO missing SIZE statement:\n{macro_text[:200]}")
    w = float(m_size.group(1))
    h = float(m_size.group(2))
    wf = f"{w:g}"
    hh = f"{h / 2.0:g}"
    hf = f"{h:g}"
    implant = (
        f"\t\tLAYER {vtn} ;\n"
        f"\t\t\tRECT 0 0 {wf} {hh} ;\n"
        f"\t\tLAYER {vtp} ;\n"
        f"\t\t\tRECT 0 {hh} {wf} {hf} ;"
    )
    if re.search(r"^\s*OBS\s*$", macro_text, re.M):
        updated, count = re.subn(
            r"(\n[ \t]*END\nEND\s+\S+\s*)$",
            "\n" + implant + r"\1",
            macro_text,
            count=1,
        )
    else:
        obs_block = f"\n\tOBS\n{implant}\n\tEND"
        updated, count = re.subn(
            r"(\nEND\s+\S+\s*)$",
            obs_block + r"\1",
            macro_text,
            count=1,
        )
    if count != 1:
        raise ValueError(f"Failed to inject OBS into MACRO:\n{macro_text[-200:]}")
    return updated


def transform_lef(text, vt_tag):
    if vt_tag == "SRAM":
        return text
    return _MACRO_RE.sub(lambda m: inject_macro_vt(m.group(1), vt_tag), text)


def main(argv):
    parser = argparse.ArgumentParser()
    parser.add_argument("--vt", required=True, choices=("R", "L", "SL", "SRAM"))
    parser.add_argument("--src", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv[1:])

    if args.vt == "SRAM":
        shutil.copyfile(args.src, args.out)
        return 0

    text = args.src.read_text(encoding="utf-8")
    args.out.write_text(transform_lef(text, args.vt), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
